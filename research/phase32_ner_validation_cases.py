from __future__ import annotations

from dataclasses import dataclass

from research.evaluation import EntitySpan


@dataclass(frozen=True, slots=True)
class ValidationDocument:
    """An immutable synthetic document with exact gold PERSON spans."""

    doc_id: str
    category: str
    description: str
    text: str
    gold_spans: tuple[EntitySpan, ...]
    whitespace_word_count: int

    def __post_init__(self) -> None:
        """Validate span bounds and invariants."""
        text_len = len(self.text)
        seen: set[tuple[int, int, str]] = set()
        for span in self.gold_spans:
            if not (0 <= span.start < span.end <= text_len):
                raise ValueError(
                    f"Doc {self.doc_id}: invalid span [{span.start}:{span.end}] "
                    f"for text length {text_len}"
                )
            if self.text[span.start : span.end] == "":
                raise ValueError(f"Doc {self.doc_id}: empty span")
            key = (span.start, span.end, span.type)
            if key in seen:
                raise ValueError(f"Doc {self.doc_id}: duplicate span {key}")
            seen.add(key)


def _span_for(
    full_text: str,
    target: str,
    entity_type: str = "PERSON",
    occurrence: int = 1,
) -> EntitySpan:
    """Find the exact (start, end) character offset of target in full_text."""
    pos = -1
    for _ in range(occurrence):
        pos = full_text.find(target, pos + 1)
        if pos == -1:
            raise ValueError(
                f"Target {target!r} (occurrence {occurrence}) not found in text"
            )
    return EntitySpan(start=pos, end=pos + len(target), type=entity_type)


