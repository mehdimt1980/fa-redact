def build_targeted_normalization_cases() -> list[ValidationDocument]:
    """Build targeted normalization validation cases.

    Covers:
    - Arabic Yeh (ي) vs Persian Yeh (ی)
    - Arabic Kaf (ك) vs Persian Kaf (ک)
    - Zero-Width Non-Joiner (ZWNJ) inside a PERSON name
    - Leading/trailing whitespace around spans in original text
    """
    cases: list[ValidationDocument] = []

    # Case 1: Arabic Yeh in person name (علي حسيني -> علي حسيني in original text)
    t1 = "بیمار محترم آقای علي حسيني جهت چکاپ به کلینیک مراجعه نمودند."
    sp1 = _span_for(t1, "علي حسيني", "PERSON")
    cases.append(
        ValidationDocument(
            doc_id="VAL_NORM_ARABIC_YEH",
            category="normalization_arabic_yeh",
            description="Arabic Yeh in person name",
            text=t1,
            gold_spans=(sp1,),
            whitespace_word_count=len(t1.split()),
        )
    )

    # Case 2: Arabic Kaf in person name (كاظمي -> كاظمي in original text)
    t2 = "ویزیت بیمار توسط خانم دکتر مریم كاظمي انجام شد."
    sp2 = _span_for(t2, "مریم كاظمي", "PERSON")
    cases.append(
        ValidationDocument(
            doc_id="VAL_NORM_ARABIC_KAF",
            category="normalization_arabic_kaf",
            description="Arabic Kaf in person name",
            text=t2,
            gold_spans=(sp2,),
            whitespace_word_count=len(t2.split()),
        )
    )

    # Case 3: ZWNJ inside a compound person name (سید‌علی)
    t3 = "پرونده بالینی آقای سید\u200cعلی محمدی بررسی گردید."
    sp3 = _span_for(t3, "سید\u200cعلی محمدی", "PERSON")
    cases.append(
        ValidationDocument(
            doc_id="VAL_NORM_ZWNJ",
            category="normalization_zwnj",
            description="ZWNJ inside compound person name",
            text=t3,
            gold_spans=(sp3,),
            whitespace_word_count=len(t3.split()),
        )
    )

    # Case 4: Person name with surrounding spaces / punctuation
    t4 = "پزشک معالج :   سارا احمدی   ، متخصص جراحی عمومی."
    sp4 = _span_for(t4, "سارا احمدی", "PERSON")
    cases.append(
        ValidationDocument(
            doc_id="VAL_NORM_SPACING",
            category="normalization_spacing",
            description="Surrounding spaces and punctuation around person name",
            text=t4,
            gold_spans=(sp4,),
            whitespace_word_count=len(t4.split()),
        )
    )

    return cases
